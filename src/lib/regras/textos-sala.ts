const DICIONARIOS: Record<Idioma, Record<ChaveTexto, string>> = { "pt-BR": PT_BR, es: ES, en: EN };

export function t(idioma: Idioma, chave: ChaveTexto, vars?: Record<string, string | number>): string {
  const dicionario = DICIONARIOS[idioma] ?? PT_BR;
  let texto = dicionario[chave] ?? PT_BR[chave];
  if (vars) {
    // Função de substituição (não a string direto): `$&`/`$1` no valor não deve ser interpretado pelo replaceAll.
    for (const [nome, valor] of Object.entries(vars)) texto = texto.replaceAll(`{${nome}}`, () => String(valor));
  }
  return texto;
}

/** Idioma da sala a partir de um atributo `lang` (o wrapper do layout da sala usa o idioma do webinar). Qualquer
 *  outra coisa (vazio, idioma que a sala não tem) cai no pt-BR. */
export function idiomaDoLang(lang: string | null | undefined): Idioma {
  return lang === "es" || lang === "en" ? lang : "pt-BR";
}
